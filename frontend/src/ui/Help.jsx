/* ================= دکمه ؟ کنار هر بخش ================= */

export function HelpButton ({ topic, label = 'راهنمای این بخش', style }) {
  const [open, setOpen] = useState(false)
  const doc = HELP_DOCS[topic]
  if (!doc) return null
  return (
    <>
      <button type="button" className="help-btn" style={style} title={`راهنما: ${doc.title}`} onClick={() => setOpen(true)}>
        <Icon name="help" size={16} />
        {label && <span className="help-btn-text">{label}</span>}
      </button>
      {open && <HelpModal topic={topic} onClose={() => setOpen(false)} />}
    </>
  )
}

export function HelpModal ({ topic, onClose }) {
  const doc = HELP_DOCS[topic]
  if (!doc) return null
  return (
    <Modal title={<span className="help-title"><Icon name="help" size={18} /> راهنمای بخش «{doc.title}»</span>} onClose={onClose}
      foot={<button className="btn btn-primary" onClick={onClose}>متوجه شدم</button>}>
      <div className="help-body">
        <div className="help-about">
          <b>این بخش چیست؟</b>
          <p>{doc.about}</p>
        </div>
        <div className="help-steps">
          <b>چگونه اقدام کنم؟</b>
          <ol>
            {doc.steps.map((s, i) => <li key={i}>{s}</li>)}
          </ol>
        </div>
        {doc.tips?.length > 0 && (
          <div className="help-tips">
            <b>نکات مهم</b>
            <ul>
              {doc.tips.map((s, i) => <li key={i}>{s}</li>)}
            </ul>
          </div>
        )}
        <div className="help-foot muted small">
          سؤال بیشتری دارید؟ «راهنمای جامع سامانه» را از نوار بالای صفحه باز کنید.
        </div>
      </div>
    </Modal>
  )
}

