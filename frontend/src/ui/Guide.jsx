export function GuideButton () {
  const [open, setOpen] = useState(false)
  // امکان بازکردن از بنر داشبورد یا لینک‌های دیگر
  useEffect(() => {
    const fn = () => setOpen(true)
    window.addEventListener('open-maliyar-guide', fn)
    return () => window.removeEventListener('open-maliyar-guide', fn)
  }, [])
  return (
    <>
      <button type="button" className="btn-guide" onClick={() => setOpen(true)} title="راهنمای جامع سامانه">
        <Icon name="book" size={16} /> راهنمای جامع
      </button>
      {open && <Guide onClose={() => setOpen(false)} />}
    </>
  )
}
